// Extracts real province geometry + piece coordinates from the jDip standard
// map (src/games/diplomacy/assets/jdip-standard.svg) into a clean data module
// (src/games/diplomacy/mapGeometry.js) keyed by OUR province IDs.
//
//   node scripts/diplomacy-extract-jdip.mjs
//
// The jDip map is GPL (SVG by Zach DelProposto, jDip project). We use ONLY its
// vector province boundaries and per-province piece coordinates — not its
// background bitmap — and recolour everything with our own theme. See
// src/games/diplomacy/assets/ATTRIBUTION.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { PROVINCES } from '../src/games/diplomacy/DiplomacyBoard.js';

const svg = readFileSync(new URL('../src/games/diplomacy/assets/jdip-standard.svg', import.meta.url), 'utf8');

// Our abbreviation -> jDip abbreviation, where they differ (same provinces).
const ALIAS = { NAO: 'nat', NWG: 'nrg', MAO: 'mid', TYS: 'tyn' };
const jidOf = (id) => ALIAS[id] || id.toLowerCase();
const REV = Object.fromEntries(Object.entries(ALIAS).map(([o, j]) => [j, o]));
const ourId = (jid) => REV[jid] || jid.toUpperCase();

const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
const transform = svg.match(/<g id="MapLayer" transform="([^"]+)">/)[1];

// ---- province path shapes ----------------------------------------------------
const paths = {};
for (const m of svg.matchAll(/<path class="([^"]*)" d="([^"]*)" id="_([a-z0-9-]+)"\s*\/>/g)) {
  paths[m[3]] = m[2].replace(/\s+/g, ' ').trim();
}

const shapes = {};
const missing = [];
for (const id of Object.keys(PROVINCES)) {
  const d = paths[jidOf(id)];
  if (d) shapes[id] = d;
  else missing.push(id);
}

// ---- per-province (and per-coast) unit coordinates ---------------------------
const unitPos = {};
for (const m of svg.matchAll(/<jdipNS:PROVINCE name="([^"]+)">([\s\S]*?)<\/jdipNS:PROVINCE>/g)) {
  const name = m[1];
  const u = m[2].match(/<jdipNS:UNIT x="([^"]+)" y="([^"]+)"\/>/);
  if (!u) continue;
  const [base, coast] = name.split('-');
  const oid = ourId(base);
  if (!PROVINCES[oid]) continue;
  const loc = coast ? `${oid}/${coast}` : oid;
  unitPos[loc] = { x: +u[1], y: +u[2] };
}

// ---- supply-center marker coordinates ----------------------------------------
const scPos = {};
for (const m of svg.matchAll(/<use[^>]*id="sc_([A-Za-z]+)"[^>]*x="([^"]+)"[^>]*y="([^"]+)"[^>]*\/>/g)) {
  const oid = ourId(m[1].toLowerCase());
  if (PROVINCES[oid]) scPos[oid] = { x: +m[2], y: +m[3] };
}

// ---- province name label coordinates -----------------------------------------
// jDip labels a few seas with a different abbreviation than its own path id
// (e.g. Gulf of Lyon: path "_gol" but label text "LYO").
const LABEL_ALIAS = { lyo: 'GOL' };
const labelId = (abbr) => LABEL_ALIAS[abbr] || ourId(abbr);
const labelPos = {};
for (const m of svg.matchAll(/<text[^>]*?x="([^"]+)"\s+y="([^"]+)"[^>]*>([A-Za-z]+)<\/text>/g)) {
  const oid = labelId(m[3].toLowerCase());
  if (PROVINCES[oid]) labelPos[oid] = { x: +m[1], y: +m[2] };
}
// Safety net: any province still without a label sits its label at its piece spot.
for (const id of Object.keys(PROVINCES)) {
  if (!labelPos[id] && unitPos[id]) labelPos[id] = { ...unitPos[id] };
}

const fmt = (obj) =>
  JSON.stringify(obj)
    .replace(/","/g, '",\n  "')
    .replace(/^\{"/, '{\n  "')
    .replace(/"\}$/, '"\n}')
    .replace(/\},"/g, '},\n  "')
    .replace(/^\{/, '{\n  ')
    .replace(/\}$/, '\n}');

const out = `// AUTO-GENERATED by scripts/diplomacy-extract-jdip.mjs — do not edit by hand.
// Real province geometry + piece coordinates from the jDip standard map,
// re-keyed to our province IDs. Regenerate with:
//   node scripts/diplomacy-extract-jdip.mjs
//
// Source: jDip "Detailed Standard Map", SVG by Zach DelProposto (GPL). Only the
// vector boundaries + coordinates are used; see assets/ATTRIBUTION.md.

export const MAP_VIEWBOX = ${JSON.stringify(viewBox)};

// Province paths are authored in the jDip MapLayer space; render them inside a
// <g transform="MAP_TRANSFORM">. Units/supply/labels below are in root space.
export const MAP_TRANSFORM = ${JSON.stringify(transform)};

export const PROVINCE_SHAPES = ${fmt(shapes)};

export const UNIT_POS = ${fmt(unitPos)};

export const SC_POS = ${fmt(scPos)};

export const LABEL_POS = ${fmt(labelPos)};
`;

writeFileSync(new URL('../src/games/diplomacy/mapGeometry.js', import.meta.url), out);
console.log(`shapes: ${Object.keys(shapes).length}/${Object.keys(PROVINCES).length} (no path for: ${missing.join(', ') || 'none'})`);
console.log(`unitPos: ${Object.keys(unitPos).length}, scPos: ${Object.keys(scPos).length}, labelPos: ${Object.keys(labelPos).length}`);
